import os
from rdkit import Chem

def split_sdf_to_individual(input_sdf_path, output_dir, protein_name):
    """
    ????????? ????????????????? SDF ?? ????????? ?????.
    ?????? ???? ?????????? {protein_name}_ligand_{i}.sdf
    ?????? ???????? ?????????? ?????.
    """
    os.makedirs(output_dir, exist_ok=True)
    suppl = Chem.SDMolSupplier(input_sdf_path, removeHs=False)

    for i, mol in enumerate(suppl, start=1):
        if mol is None:
            print(f"Warning: mol {i} ?? ?????????, ??????????.")
            continue

        ligand_name = f"{protein_name}_ligand_{i}"
        mol.SetProp("_Name", ligand_name)

        output_path = os.path.join(output_dir, f"{ligand_name}.sdf")

        writer = Chem.SDWriter(output_path)
        writer.write(mol)
        writer.close()

        print(f"???????? {ligand_name} ? {output_path}")

if __name__ == "__main__":
    input_sdf = "ligand/CYP2d6_ic50.sdf"  # ???? ? ????????? SDF ? ?????????? ????????
    output_folder = "ligand/ligands_4wnv_ic50"  # ????? ??? ????????? ??????
    protein_name = "4wnv"  # ??? ?????, ??????? ????? ????????? ? ??? ?????? ? ???????

    split_sdf_to_individual(input_sdf, output_folder, protein_name)
